XLSX_HEADERS = ["성명", "소속", "부서", "직위", "전문분야", "휴대전화", "이메일"]


def specialty_name(specialty_id: str) -> str:
    """전문분야 id → 표시 이름. 모르는 id는 그대로 돌려준다."""
    for item in SPECIALTIES:
        if item["id"] == specialty_id:
            return item["name"]
    return str(specialty_id)


def write_pool_xlsx(path, members) -> None:
    """members를 서비스 등록 서식(.xlsx)으로 저장한다. 수식 없음, 값만 기록."""
    from openpyxl import Workbook
    from openpyxl.styles import Font
    from openpyxl.utils import get_column_letter

    book = Workbook()
    sheet = book.active
    sheet.title = "평가위원"
    sheet.append(XLSX_HEADERS)
    for cell in sheet[1]:
        cell.font = Font(bold=True)
    for member in members:
        sheet.append(
            [
                member["name"],
                member["organization_name"],
                member["department_name"],
                member["position"],
                ", ".join(specialty_name(sid) for sid in member["specialty_ids"]),
                member["phone"],
                member["email"],
            ]
        )
    for index in range(1, len(XLSX_HEADERS) + 1):
        sheet.column_dimensions[get_column_letter(index)].width = 24
    book.save(str(path))
